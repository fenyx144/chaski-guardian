const DICCIONARIOS: Record<Lang, Record<Clave, string>> = { es, en, qu };

interface IdiomaCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (clave: Clave, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<IdiomaCtx>({
  lang: "es",
  setLang: () => undefined,
  t: (c) => es[c],
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es");

  useEffect(() => {
    try {
      const g = localStorage.getItem("chaski-lang");
      if (g === "en" || g === "es" || g === "qu") setLangState(g);
    } catch {
      /* sin almacenamiento */
    }
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("chaski-lang", l);
    } catch {
      /* sin almacenamiento */
    }
    document.documentElement.lang = l;
  };

  const t = (clave: Clave, vars?: Record<string, string | number>) => {
    let s = DICCIONARIOS[lang][clave] ?? es[clave] ?? clave;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useIdioma(): IdiomaCtx {
  return useContext(Ctx);
}
